def test_event_contract_and_tenant_integrity(dataset):
    required = {
        "timestamp",
        "tenant_id",
        "integration_id",
        "integration_name",
        "integration_type",
        "request_id",
        "http_status",
        "latency_ms",
        "error_code",
        "error_message",
    }
    ids = set()
    series = set()
    specs = {x.id: x for x in CATALOG}
    for event in dataset:
        assert required <= event.keys()
        assert event["request_id"] not in ids
        ids.add(event["request_id"])
        series.add((event["tenant_id"], event["integration_id"]))
        assert (
            DEFAULT_START
            <= datetime.fromisoformat(event["timestamp"])
            < DEFAULT_START + timedelta(minutes=60)
        )
        assert event["integration_name"] == specs[event["integration_id"]].name
        assert event["latency_ms"] > 0
        failed = event["http_status"] >= 400
        assert (event["error_code"] is not None) == failed
        assert (event["error_message"] is not None) == failed
        if event["timed_out"]:
            assert event["http_status"] == 504 and event["latency_ms"] == 30000
        # Existing ingestion remains strict; rich export metadata is deliberately stripped.
        validated = LogInput.model_validate(to_ingestion_event(event))
        assert validated.event_id == event["request_id"]
    assert len(series) == 20
    assert {x["tenant_id"] for x in dataset} == {"brightline", "tenant-002"}
    assert {x["scenario"] for x in dataset} == set(SCENARIOS)


def test_byte_reproducibility_and_sample_manifest(tmp_path):
    first = tmp_path / "first"
    second = tmp_path / "second"
    write_dataset(first, duration_minutes=60, tenants=2)
    write_dataset(second, duration_minutes=60, tenants=2)
    for filename in ("requests.jsonl", "manifest.json"):
        assert (first / filename).read_bytes() == (second / filename).read_bytes()
    manifest = json.loads((first / "manifest.json").read_text())
    assert (
        manifest["requests_sha256"]
        == hashlib.sha256((first / "requests.jsonl").read_bytes()).hexdigest()
    )
    assert manifest["event_count"] == sum(manifest["events_by_scenario"].values())
    # The committed sample is regenerated by the documented command, not hand-edited.
    from pathlib import Path

    sample = Path(__file__).resolve().parents[2] / "data/synthetic/sample"
    assert (sample / "requests.jsonl").read_bytes() == (
        first / "requests.jsonl"
    ).read_bytes()
    assert (sample / "manifest.json").read_bytes() == (
        first / "manifest.json"
    ).read_bytes()


