@pytest.mark.parametrize("scenario", SCENARIOS)
def test_scenario_health_and_incident_outcomes(db, dataset, scenario):
    events = [
        e
        for e in dataset
        if e["tenant_id"] == "brightline" and e["scenario"] == scenario
    ]
    for event in events:
        row = LogInput.model_validate(to_ingestion_event(event)).model_dump()
        row["integration_id"] = "payroll"
        db.add(RequestLog(tenant_id="a", **row))
    # Tests use the provider's actual target, as the demo does.
    from app.models.entities import Integration

    db.get(Integration, ("a", "payroll")).latency_target_ms = events[0][
        "latency_target_ms"
    ]
    db.commit()
    for offset in range(5, 61, 5):
        refresh(db, "a", DEFAULT_START + timedelta(minutes=offset))
    history = db.scalars(select(Snapshot).order_by(Snapshot.bucket)).all()
    incidents = db.scalars(select(Incident)).all()
    states = [s.status for s in history]
    if scenario in ("healthy", "brief_spike"):
        assert set(states) == {"HEALTHY"} and incidents == []
    elif scenario == "low_traffic":
        assert set(states) == {"UNKNOWN"} and incidents == []
    elif scenario == "latency_only_degradation":
        assert states[:3] == ["DEGRADED", "DEGRADED", "UNHEALTHY"]
        assert all(s.evidence["metrics"]["error_rate"] == 0 for s in history)
        assert len(incidents) == 1 and incidents[0].resolved_at is None
    elif scenario == "recovery_after_incident":
        assert "UNHEALTHY" in states and states[-2:] == ["HEALTHY", "HEALTHY"]
        assert len(incidents) == 1 and incidents[0].resolved_at is not None
    else:
        assert "UNHEALTHY" in states
        assert len(incidents) == 1 and incidents[0].resolved_at is None
        if scenario == "sustained_bad_windows":
            breach, _ = phase_bounds(60)
            # First bad window is pending; subsequent adjacent bad windows confirm.
            assert all(
                s.status == "UNHEALTHY"
                for s in history
                if utc(s.bucket) >= DEFAULT_START + timedelta(minutes=breach + 10)
            )


def test_demo_seed_is_offline_and_preserves_existing_tenants(tmp_path, monkeypatch):
    from app.models.entities import Tenant
    from sqlalchemy import create_engine, func
    from sqlalchemy.orm import Session

    from scripts import seed as demo

    engine = create_engine(f"sqlite:///{tmp_path / 'demo.db'}")
    monkeypatch.setattr(demo, "get_engine", lambda: engine)
    demo.seed(tenants=2, duration_minutes=60)
    with Session(engine) as session:
        tenants = session.scalar(select(func.count()).select_from(Tenant))
        events = session.scalar(select(func.count()).select_from(RequestLog))
        snapshots = session.scalar(select(func.count()).select_from(Snapshot))
    assert tenants == 2 and events > 1000 and snapshots == 240
    demo.seed(tenants=2, duration_minutes=60)
    with Session(engine) as session:
        assert session.scalar(select(func.count()).select_from(RequestLog)) == events
    engine.dispose()
